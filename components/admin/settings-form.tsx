"use client";

import * as React from "react";
import { Settings, settingsSchema } from "@/lib/schemas/settings";
import { updateSettings } from "@/lib/actions/settings";
import { useForm, SubmitHandler } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import { Loader2, Save, Check } from "lucide-react";
import {
  Card,
  CardHeader,
  CardTitle,
  CardDescription,
  CardContent,
} from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Button } from "@/components/ui/button";
import { Alert, AlertTitle, AlertDescription } from "@/components/ui/alert";
import { Field, FieldLabel, FieldError } from "@/components/ui/field";
import { toast } from "@/components/ui/toast";

interface SettingsFormProps {
  initialSettings: Settings;
}

export function SettingsForm({ initialSettings }: SettingsFormProps) {
  const [isPending, startTransition] = React.useTransition();
  const [savedSuccess, setSavedSuccess] = React.useState(false);

  const {
    register,
    handleSubmit,
    formState: { errors },
  } = useForm<Settings>({
    resolver: zodResolver(settingsSchema),
    defaultValues: initialSettings,
  });

  const onSubmit: SubmitHandler<Settings> = (data) => {
    setSavedSuccess(false);
    startTransition(async () => {
      try {
        await updateSettings(data);
        setSavedSuccess(true);
        toast.add({
          title: "Settings Saved",
          description: "System parameters updated successfully.",
          type: "success",
        });
        setTimeout(() => setSavedSuccess(false), 3000);
      } catch (err: unknown) {
        toast.add({
          title: "Save Failed",
          description: err instanceof Error ? err.message : String(err),
          type: "error",
        });
      }
    });
  };

  return (
    <form onSubmit={handleSubmit(onSubmit)} className="flex flex-col gap-8 max-w-3xl">
      {savedSuccess && (
        <Alert>
          <Check />
          <AlertTitle>Settings Saved</AlertTitle>
          <AlertDescription>
            Brand and WhatsApp destination coordinates updated successfully.
          </AlertDescription>
        </Alert>
      )}

      {/* WhatsApp Configuration Spotlight */}
      <Card>
        <CardHeader>
          <CardTitle>WhatsApp Destination Number</CardTitle>
          <CardDescription>
            This phone number receives all prefilled product enquiries generated by clients across the website.
          </CardDescription>
        </CardHeader>

        <CardContent>
          <Field>
            <FieldLabel htmlFor="settings-whatsapp">
              WhatsApp Number (with International Country Code, digits only)
            </FieldLabel>
            <Input
              id="settings-whatsapp"
              {...register("whatsappNumber")}
              placeholder="e.g. 447123456789"
            />
            {errors.whatsappNumber && (
              <FieldError>{errors.whatsappNumber.message}</FieldError>
            )}
          </Field>
        </CardContent>
      </Card>

      {/* Brand Identity */}
      <Card>
        <CardHeader>
          <CardTitle>Brand Identity &amp; Copy</CardTitle>
        </CardHeader>
        <CardContent>
          <div className="flex flex-col gap-4">
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <Field>
                <FieldLabel htmlFor="settings-brand-name">Brand Name</FieldLabel>
                <Input id="settings-brand-name" {...register("brandName")} />
              </Field>

              <Field>
                <FieldLabel htmlFor="settings-descriptor">Descriptor</FieldLabel>
                <Input id="settings-descriptor" {...register("descriptor")} />
              </Field>
            </div>

            <Field>
              <FieldLabel htmlFor="settings-tagline">Official Tagline</FieldLabel>
              <Input id="settings-tagline" {...register("tagline")} />
            </Field>
          </div>
        </CardContent>
      </Card>

      {/* Contact Coordinates */}
      <Card>
        <CardHeader>
          <CardTitle>Contact Coordinates &amp; Hours</CardTitle>
        </CardHeader>
        <CardContent>
          <div className="flex flex-col gap-4">
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <Field>
                <FieldLabel htmlFor="settings-email">Contact Email</FieldLabel>
                <Input
                  id="settings-email"
                  type="email"
                  {...register("contactEmail")}
                />
              </Field>

              <Field>
                <FieldLabel htmlFor="settings-phone">Direct Telephone</FieldLabel>
                <Input
                  id="settings-phone"
                  {...register("phone")}
                />
              </Field>
            </div>

            <Field>
              <FieldLabel htmlFor="settings-address">Atelier Address</FieldLabel>
              <Input
                id="settings-address"
                {...register("address")}
              />
            </Field>
          </div>
        </CardContent>
      </Card>

      {/* Social Links */}
      <Card>
        <CardHeader>
          <CardTitle>Social Links</CardTitle>
        </CardHeader>
        <CardContent>
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
            <Field>
              <FieldLabel htmlFor="settings-instagram">Instagram</FieldLabel>
              <Input
                id="settings-instagram"
                {...register("socialLinks.instagram")}
              />
            </Field>
            <Field>
              <FieldLabel htmlFor="settings-pinterest">Pinterest</FieldLabel>
              <Input
                id="settings-pinterest"
                {...register("socialLinks.pinterest")}
              />
            </Field>
            <Field>
              <FieldLabel htmlFor="settings-facebook">Facebook</FieldLabel>
              <Input
                id="settings-facebook"
                {...register("socialLinks.facebook")}
              />
            </Field>
          </div>
        </CardContent>
      </Card>

      {/* Submit Button */}
      <div className="flex justify-end">
        <Button
          type="submit"
          disabled={isPending}
          size="lg"
        >
          {isPending ? (
            <Loader2 data-icon="inline-start" className="animate-spin" />
          ) : (
            <Save data-icon="inline-start" />
          )}
          <span>Save Settings</span>
        </Button>
      </div>
    </form>
  );
}
